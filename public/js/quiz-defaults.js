/* ============================================================
   quiz-defaults.js — 新人小測驗的預設題目與欄位上限
   ------------------------------------------------------------
   quiz.html 與 admin.html 各自用 <script defer> 直接載入，
   全域只留 QUIZ_DEFAULTS 與 QUIZ_LIMITS 兩個常數（和 cropper.js 同一套做法）。

   這份題目有兩個身分：
     1. 賓客那一側的退路 —— Firestore 的 quiz 集合還是空的
        （新人還沒進後台設定）時，測驗頁就先用這 3 題，
        頁面一開就有東西可以玩，不會是空白的。
     2. 後台的起點 —— 新人第一次打開後台「測驗」分頁時，
        這 3 題會被寫進自己站台的 quiz 集合，之後改題目、改選項、
        調順序、刪掉都可以，不會影響其他新人。

   欄位格式（與 Firestore 的 quiz 集合一致）：
     type   'single' 單選 ／ 'multi' 複選（全對才得分）
     q      題目
     opts   四個選項
     answer 正確答案的索引陣列，0 = 第一個選項；單選只有一個元素
============================================================ */

